"""Generate core/src/builtin_models.inc from proto/models/*.json (the header is committed).
    python core/tools/gen_builtin_models.py"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
models = sorted((ROOT / "proto" / "models").glob("*.json"))
out = ["// GENERATED by core/tools/gen_builtin_models.py from proto/models/*.json. Do not edit.",
       "struct Builtin {", "    const char* name;", "    const char* json;", "};", "const Builtin kBuiltins[] = {"]
for p in models:
    text = json.dumps(json.loads(p.read_text(encoding="utf-8")), separators=(",", ":"))
    assert '"' not in p.stem and ")json" not in text
    chunks = [text[i:i + 1500] for i in range(0, len(text), 1500)]   # MSVC: keep each literal short
    out.append(f'    {{"{p.stem}",')
    out.extend(f'     R"json({c})json"' for c in chunks)
    out[-1] += "},"
out.append("};")
dst = ROOT / "core" / "src" / "builtin_models.inc"
dst.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {len(models)} models to {dst}")
